export function getVehicleModels(make) {
  const normalizedMake = make?.trim().toLowerCase();
  if (!normalizedMake) return [];
  const matchedMake = VEHICLE_MAKES.find(
    (candidate) => candidate.toLowerCase() === normalizedMake,
  );
  return matchedMake ? US_VEHICLE_CATALOG[matchedMake] : [];
}
